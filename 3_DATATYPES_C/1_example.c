#include<stdio.h>
int main()
{
    int mynum = 90; // here int is a data type
    float myfloatnum = 9.9; // here float is a data type
    char mychar = 'A'; // here char is a data type

    printf("mynum: %d\n",mynum);
    printf("myfloatnum: %f\n",myfloatnum);
    printf("mychar: %c", mychar);

    return 0;
}