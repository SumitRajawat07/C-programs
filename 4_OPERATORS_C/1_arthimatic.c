#include<stdio.h>
int main()
{
    int x=9;
    int y=8;

    // ARTHIMATIC OPERATOR (+,-,*,%,/,++,--)

    printf("the sum of x and y is : %d\n",x+y);
    printf("the subraction of x and y is : %d\n" , x-y);
    printf("the multiplication of x and y is : %d\n",x*y);
    printf("the modulus of x and y is : %d\n",x%y);
    printf("the division of x and y is : %d\n",x/y);
    printf("the increment of x is : %d\n", ++x);
    printf("the decrement of x is : %d\n",--x);
    printf("the increment of y is : %d\n",++y);
    printf("the decrement of y is : %d",--y);

    return 0;

}